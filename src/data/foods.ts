export const FOOD_BY_ID: Record<string, Food> = Object.fromEntries(
  FOODS.map((food) => [food.id, food]),
);

export function getFood(id: string): Food | undefined {
  return FOOD_BY_ID[id];
}

export const DIET_LABELS: Record<FoodPreference, string> = {
  veg: "Pure veg",
  egg: "Veg + egg",
  "non-veg": "Non-veg",
};

const DIET_ORDER = { veg: 0, egg: 1, "non-veg": 2 } as const;

export function isFoodCompatible(
  food: Food,
  preference: FoodPreference,
): boolean {
  return DIET_ORDER[food.diet] <= DIET_ORDER[preference];
}

export function foodsFor(
  mealType: MealType,
  preference: FoodPreference,
): Food[] {
  return FOODS.filter(
    (food) =>
      food.mealType === mealType && isFoodCompatible(food, preference),
  );
}

